export const PopoverContainer = () => {
  const [show, setShow] = useState(true);
  const containerRef = useRef(null);
  const popover = <Popover id="popover-container">
      <Popover.Header as="h3">Popover title</Popover.Header>
      <Popover.Body>And here's some amazing content. It's very engaging. Right?</Popover.Body>
    </Popover>;
  return <ComponentCard title={<h2>
          Popover
          <span className="fw-300">
            <i>Container</i>
          </span>
        </h2>} toolbox>
      <div className="panel-container show">
        <div className="panel-content">
          <div className="panel-tag">
            Appends the popover to a specific element. Example: <code>container: 'body'</code>. This option is particularly useful in that it allows
            you to position the popover in the flow of the document near the triggering element -&nbsp;which will prevent the popover from floating
            away from the triggering element during a window resize
          </div>
          <div className="d-flex align-items-end">
            <OverlayTrigger trigger="click" container={containerRef} overlay={popover}>
              <Button variant="secondary">Display popover</Button>
            </OverlayTrigger>
            <Button variant="success" className="btn-xs ms-auto" onClick={() => setShow(!show)}>
              hide container
            </Button>
          </div>
          {show && <div ref={containerRef} className="p-3 rounded bg-warning-100 mt-3 js-test-container">
              The popover is nested inside this container but displayed on the element above. Once this container is hidden the popover will not be
              visible. Try hiding this container by pressing the "hide" button above
            </div>}
        </div>
      </div>
    </ComponentCard>;
};
